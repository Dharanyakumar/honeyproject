"""Spectral second-opinion model.

A near-infrared (NIR) spectrum is a list of 61 absorbance readings from 1100 to 2300 nm. Honey has strong
water and sugar bands; syrup adulteration changes their heights and shifts a few of them. The model is
SNV normalisation -> PCA (8 components) -> logistic regression, a standard chemometrics recipe.

The spectra here are SYNTHETIC (Gaussian bands plus noise), built to behave like published NIR honey
studies. Replace generate() with measured spectra from a lab spectrometer before trusting the accuracy.
"""
import json
import threading
from pathlib import Path

import joblib
import numpy as np
from sklearn.decomposition import PCA
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score
from sklearn.model_selection import cross_val_score, train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import FunctionTransformer

BASE = Path(__file__).parent
MODEL_FILE = BASE / "ml" / "spectral_model.joblib"
METRICS_FILE = BASE / "ml" / "spectral_metrics.json"

WAVELENGTHS = np.arange(1100, 2301, 20)   # 61 points, nm
N_POINTS = len(WAVELENGTHS)
MODEL = METRICS = None
_lock = threading.Lock()

# (centre nm, width nm, height) of the main bands in pure honey
_BANDS = [(1200, 40, 0.10), (1450, 40, 0.55), (1580, 45, 0.25), (1690, 30, 0.12),
          (1940, 50, 1.00), (2100, 60, 0.50), (2270, 50, 0.40)]


class SpectrumError(ValueError):
    pass


def snv(X):
    """Standard normal variate: removes brightness and slope differences between samples."""
    X = np.asarray(X, dtype=float)
    return (X - X.mean(axis=1, keepdims=True)) / (X.std(axis=1, keepdims=True) + 1e-9)


def _spectrum(rng, strength):
    """One spectrum. strength 0 = pure honey, 1 = clearly adulterated, in between = light adulteration."""
    y = rng.normal(0.05, 0.02) + rng.normal(0, 0.00004) * (WAVELENGTHS - 1700)
    for centre, width, height in _BANDS:
        h = height * rng.normal(1.0, 0.10)
        c = centre
        if strength:
            if centre == 1940:
                h *= 1 + 0.16 * strength     # more water
            if centre == 2100:
                c -= 12 * strength           # sucrose-like shift
                h *= 1 + 0.25 * strength
            if centre == 1690:
                h *= 1 + 0.55 * strength
            if centre == 1580:
                h *= 1 - 0.18 * strength     # less fructose and glucose
        y = y + h * np.exp(-0.5 * ((WAVELENGTHS - c) / width) ** 2)
    if strength:
        y = y + 0.10 * strength * rng.normal(1.0, 0.1) * np.exp(-0.5 * ((WAVELENGTHS - 1760) / 35) ** 2)
    return y + rng.normal(0, 0.02, N_POINTS)


def generate(n_per_class=600, seed=5):
    rng = np.random.default_rng(seed)
    pure = [_spectrum(rng, 0) for _ in range(n_per_class)]
    adult = [_spectrum(rng, rng.choice([0.35, 1.0], p=[0.4, 0.6]) * rng.uniform(0.8, 1.1))
             for _ in range(n_per_class)]
    X = np.array(pure + adult)
    y = np.array([0] * n_per_class + [1] * n_per_class)
    return X, y


def train():
    X, y = generate()
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2, stratify=y, random_state=7)
    model = make_pipeline(FunctionTransformer(snv), PCA(n_components=8, random_state=7),
                          LogisticRegression(max_iter=2000))
    model.fit(X_tr, y_tr)
    pred = model.predict(X_te)
    cv = cross_val_score(model, X, y, cv=5, scoring="f1")
    metrics = {
        "accuracy": round(float(accuracy_score(y_te, pred)), 4),
        "f1": round(float(f1_score(y_te, pred)), 4),
        "cv_f1_mean": round(float(cv.mean()), 4),
        "confusion_matrix": confusion_matrix(y_te, pred).tolist(),
        "n_samples": int(len(y)), "train_size": int(len(y_tr)), "test_size": int(len(y_te)),
        "points": N_POINTS, "range_nm": [int(WAVELENGTHS[0]), int(WAVELENGTHS[-1])],
        "source": "Synthetic NIR spectra generated by the project", "synthetic": True,
    }
    return model, metrics


def _load():
    global MODEL, METRICS
    try:
        MODEL = joblib.load(MODEL_FILE)
        METRICS = json.loads(METRICS_FILE.read_text())
        return
    except Exception:
        pass  # missing, or saved by a different scikit-learn version: train again
    MODEL, METRICS = train()
    try:
        MODEL_FILE.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(MODEL, MODEL_FILE)
        METRICS_FILE.write_text(json.dumps(METRICS, indent=2))
    except OSError:
        pass  # read-only folder: keep the model in memory only


def parse(raw):
    """Accept a list of 61 numbers (or a string of numbers separated by commas, spaces or new lines)."""
    if isinstance(raw, str):
        raw = [t for t in raw.replace(",", " ").replace(";", " ").split()]
    if not isinstance(raw, (list, tuple)):
        raise SpectrumError("Send the spectrum as a list of numbers.")
    try:
        vals = [float(v) for v in raw]
    except (TypeError, ValueError):
        raise SpectrumError("Every spectrum value must be a number.")
    if len(vals) != N_POINTS:
        raise SpectrumError(f"Expected {N_POINTS} readings (1100 to 2300 nm, every 20 nm), got {len(vals)}.")
    arr = np.array(vals)
    if not np.all(np.isfinite(arr)) or arr.min() < -1 or arr.max() > 5:
        raise SpectrumError("Absorbance values must be between -1 and 5.")
    if arr.std() < 1e-6:
        raise SpectrumError("The spectrum is flat. Check the file.")
    return arr


def predict(arr):
    with _lock:
        p = float(MODEL.predict_proba(np.asarray(arr).reshape(1, -1))[0][1])
    bad = p >= 0.5
    return dict(verdict="Adulterated" if bad else "Pure",
                confidence=round((p if bad else 1 - p) * 100, 1), p_adulterated=round(p * 100, 1))


def _samples():
    rng = np.random.default_rng(2026)
    return {"pure": [round(float(v), 4) for v in _spectrum(rng, 0)],
            "adulterated": [round(float(v), 4) for v in _spectrum(rng, 1.0)]}


SAMPLES = _samples()
_load()
