"""Model training, loading and prediction for honey quality."""
import io
import json
import threading
from pathlib import Path

import joblib
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score
from sklearn.model_selection import cross_val_score, train_test_split

from ml.generate_dataset import FEATURES, build

BASE = Path(__file__).parent
MODEL_FILE = BASE / "ml" / "model.joblib"
METRICS_FILE = BASE / "ml" / "metrics.json"

MODEL = METRICS = None

# ---- CORE (also copied into the single-file build) ----
_model_lock = threading.Lock()
MIN_ROWS, MIN_PER_CLASS = 40, 15


class ValidationError(ValueError):
    pass


def train_model(df, source):
    X = df[FEATURES]
    y = (df.label == "Adulterated").astype(int)
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2, stratify=y, random_state=7)
    model = RandomForestClassifier(n_estimators=300, max_depth=10, random_state=7, n_jobs=-1)
    model.fit(X_tr, y_tr)
    pred = model.predict(X_te)
    cv = cross_val_score(model, X, y, cv=5, scoring="f1")
    metrics = {
        "accuracy": round(float(accuracy_score(y_te, pred)), 4),
        "f1": round(float(f1_score(y_te, pred)), 4),
        "cv_f1_mean": round(float(cv.mean()), 4),
        "confusion_matrix": confusion_matrix(y_te, pred).tolist(),
        "feature_importance": {f: round(float(v), 4) for f, v in
                               sorted(zip(FEATURES, model.feature_importances_), key=lambda t: -t[1])},
        "n_samples": int(len(df)),
        "n_pure": int((y == 0).sum()),
        "n_adulterated": int((y == 1).sum()),
        "train_size": int(len(X_tr)),
        "test_size": int(len(X_te)),
        "source": source,
        "synthetic": source.startswith("Synthetic"),
    }
    return model, metrics


def _save_model():
    MODEL_FILE.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"model": MODEL, "features": FEATURES}, MODEL_FILE)
    METRICS_FILE.write_text(json.dumps(METRICS, indent=2))


def _load_model():
    """Load the saved model, or train one from the synthetic dataset on first run."""
    global MODEL, METRICS
    try:
        MODEL = joblib.load(MODEL_FILE)["model"]
        METRICS = json.loads(METRICS_FILE.read_text())
        if "confusion_matrix" in METRICS and "source" in METRICS:
            return
    except Exception:
        pass  # missing or saved by a different scikit-learn version: train again
    MODEL, METRICS = train_model(build(), "Synthetic dataset generated by the project")
    _save_model()


def parse_dataset(raw: bytes):
    """Read an uploaded CSV: the 7 feature columns plus a label column (Pure / Adulterated)."""
    try:
        df = pd.read_csv(io.BytesIO(raw))
    except Exception:
        raise ValidationError("Could not read the file. Upload a CSV with a header row.")
    df.columns = [str(c).strip().lower().replace(" ", "_") for c in df.columns]
    missing = [c for c in FEATURES + ["label"] if c not in df.columns]
    if missing:
        raise ValidationError("Missing columns: " + ", ".join(missing) + ".")
    df = df[FEATURES + ["label"]].copy()
    df["label"] = df["label"].astype(str).str.strip().str.lower().map(
        {"pure": "Pure", "adulterated": "Adulterated"})
    for f in FEATURES:
        df[f] = pd.to_numeric(df[f], errors="coerce")
    before = len(df)
    df = df.dropna().reset_index(drop=True)
    counts = df.label.value_counts()
    if len(df) < MIN_ROWS or counts.get("Pure", 0) < MIN_PER_CLASS or counts.get("Adulterated", 0) < MIN_PER_CLASS:
        raise ValidationError(
            f"Not enough usable rows. Need at least {MIN_PER_CLASS} Pure and {MIN_PER_CLASS} Adulterated "
            f"rows with every value filled in. Found {int(counts.get('Pure', 0))} Pure and "
            f"{int(counts.get('Adulterated', 0))} Adulterated.")
    return df, before - len(df)


def retrain(df, source):
    global MODEL, METRICS
    model, metrics = train_model(df, source)
    with _model_lock:
        MODEL, METRICS = model, metrics
        _save_model()
    return metrics


# Standard limits (Codex Alimentarius / BIS IS 4941). lo/hi = acceptable bounds.
FIELDS = [
    dict(key="moisture", label="Moisture", unit="%", lo=None, hi=20, min=5, max=40, step=0.1,
         help="Max 20 %"),
    dict(key="ph", label="pH", unit="", lo=3.4, hi=4.5, min=2, max=7, step=0.01,
         help="Typically 3.4 to 4.5"),
    dict(key="conductivity", label="Electrical conductivity", unit="mS/cm", lo=None, hi=0.8,
         min=0.01, max=2, step=0.01, help="Max 0.8 for blossom honey"),
    dict(key="hmf", label="HMF", unit="mg/kg", lo=None, hi=40, min=0, max=250, step=0.5,
         help="Max 40 (indicates heating or age)"),
    dict(key="reducing_sugar", label="Reducing sugars", unit="%", lo=60, hi=None, min=30, max=85,
         step=0.1, help="Min 60 %"),
    dict(key="sucrose", label="Sucrose", unit="%", lo=None, hi=5, min=0, max=30, step=0.1,
         help="Max 5 %"),
    dict(key="diastase", label="Diastase activity", unit="DN", lo=8, hi=None, min=0, max=40,
         step=0.5, help="Min 8 Schade units"),
]

SAMPLES = {
    "pure": dict(moisture=17.4, ph=3.9, conductivity=0.46, hmf=14, reducing_sugar=68.2,
                 sucrose=1.8, diastase=15.5),
    "adulterated": dict(moisture=22.6, ph=4.3, conductivity=0.27, hmf=61, reducing_sugar=57.4,
                        sucrose=9.7, diastase=5.2),
}


def parse(raw: dict) -> dict:
    values = {}
    for f in FIELDS:
        try:
            v = float(raw.get(f["key"]))
        except (TypeError, ValueError):
            raise ValidationError(f"{f['label']} must be a number.")
        if not f["min"] <= v <= f["max"]:
            raise ValidationError(f"{f['label']} must be between {f['min']} and {f['max']}.")
        values[f["key"]] = v
    return values


def compliance(values: dict) -> list:
    rows = []
    for f in FIELDS:
        v = values[f["key"]]
        ok = (f["lo"] is None or v >= f["lo"]) and (f["hi"] is None or v <= f["hi"])
        rows.append(dict(key=f["key"], label=f["label"], unit=f["unit"], value=v, ok=ok,
                         limit=f["help"]))
    return rows


def predict(values: dict) -> dict:
    X = pd.DataFrame([[values[k] for k in FEATURES]], columns=FEATURES)
    p_adult = float(MODEL.predict_proba(X)[0][1])
    adulterated = p_adult >= 0.5
    confidence = p_adult if adulterated else 1 - p_adult
    checks = compliance(values)
    failed = [c["label"] for c in checks if not c["ok"]]
    if adulterated:
        grade = "Rejected"
    elif not failed and confidence >= 0.9:
        grade = "A"
    else:
        grade = "B"
    return dict(
        verdict="Adulterated" if adulterated else "Pure",
        grade=grade,
        confidence=round(confidence * 100, 1),
        p_adulterated=round(p_adult * 100, 1),
        checks=checks,
        failed=failed,
    )


# ---- END CORE ----
_load_model()
